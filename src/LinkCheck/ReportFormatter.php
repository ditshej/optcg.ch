<?php

declare(strict_types=1);

namespace Optcg\LinkCheck;

/**
 * Turns LinkChecker results into the two reports bin/check-links.php needs:
 * a short human summary for the terminal/Action log, and a Markdown report
 * the weekly workflow puts into a GitHub issue (docs/plan.md section 6).
 */
final class ReportFormatter
{
    /**
     * @param list<LinkCheckResult> $results
     */
    public function summary(array $results): string
    {
        $dead = $this->deadLinks($results);
        $lines = [sprintf('Checked %d link(s), %d dead.', count($results), count($dead))];

        foreach ($dead as $result) {
            $lines[] = sprintf('- DEAD %s/%s: %s -> %s', $result->roomId, $result->linkId, $result->url, $result->reason());
        }

        return implode("\n", $lines);
    }

    /**
     * @param list<LinkCheckResult> $results
     */
    public function markdownReport(array $results, string $checkedAtUtc): string
    {
        $dead = $this->deadLinks($results);

        $lines = [
            '# Weekly link check',
            '',
            sprintf(
                'Checked %d link(s) on %s. %d link(s) are unreachable.',
                count($results),
                $checkedAtUtc,
                count($dead),
            ),
        ];

        if ($dead !== []) {
            $lines[] = '';
            $lines[] = '## Dead links';
            $lines[] = '';

            foreach ($dead as $result) {
                $lines[] = sprintf(
                    '- **%s / %s** (%s) — `%s` — %s',
                    $result->roomId,
                    $result->linkId,
                    $result->title,
                    $result->url,
                    $result->reason(),
                );
            }
        }

        $lines[] = '';
        $lines[] = '_Generated by `bin/check-links.php`. Fix the link in `data/links/<room-id>.yaml` '
            . 'or remove it, then close this issue._';

        return implode("\n", $lines);
    }

    /**
     * @param list<LinkCheckResult> $results
     * @return list<LinkCheckResult>
     */
    public function deadLinks(array $results): array
    {
        return array_values(array_filter($results, static fn (LinkCheckResult $result): bool => !$result->ok));
    }
}
